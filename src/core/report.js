import { ruleText } from './forge.js';
import { truncate } from './text.js';

const fmtInt = (n) => Math.round(n || 0).toLocaleString('en-US');
const fmtTokens = (n) => (n >= 1e9 ? `${(n / 1e9).toFixed(2)}B` : n >= 1e6 ? `${(n / 1e6).toFixed(1)}M` : n >= 1e3 ? `${Math.round(n / 1e3)}k` : String(Math.round(n || 0)));
const fmtUsd = (n) => `$${(n || 0).toLocaleString('en-US', { maximumFractionDigits: n >= 100 ? 0 : 2 })}`;
const date = (iso) => (iso ? new Date(iso).toISOString().slice(0, 10) : '–');

const SUGGESTION_LABEL = { rule: 'CLAUDE.md rule', skill: 'Skill', hook: 'Hook', subagent: 'Subagent', command: 'Slash command' };

/** A shareable Markdown retrospective of how you work with Claude Code. */
export function buildReport({ overview, patterns, health, sessions }) {
  const t = overview.totals;
  const lines = [];
  lines.push('# Claude Code retrospective');
  lines.push('');
  lines.push(`Generated by Tacit on ${new Date().toISOString().slice(0, 10)} from local history (${date(overview.range.first)} to ${date(overview.range.last)}).`);
  lines.push('');
  lines.push('## At a glance');
  lines.push('');
  lines.push('| | |');
  lines.push('|---|---|');
  lines.push(`| Sessions | ${fmtInt(t.sessions)} across ${fmtInt(t.projects)} projects |`);
  lines.push(`| Your prompts | ${fmtInt(t.prompts)} |`);
  lines.push(`| Active time | ${t.activeHours.toFixed(1)} hours |`);
  lines.push(`| Tokens processed | ${fmtTokens(t.tokens)} (${fmtTokens(t.outputTokens)} written by Claude) |`);
  lines.push(`| API-equivalent cost | ${fmtUsd(t.costUSD)} |`);
  lines.push(`| Prompt cache hit rate | ${(t.cacheHitRate * 100).toFixed(1)}% (saved about ${fmtUsd(t.cacheSavedUSD)}) |`);
  lines.push(`| Subagent runs | ${fmtInt(t.subagentRuns)} |`);
  lines.push(`| Compactions | ${fmtInt(t.compactions)} |`);
  lines.push('');

  const habits = patterns.filter((p) => p.kind !== 'brief').slice(0, 12);
  if (habits.length) {
    lines.push('## What you keep telling Claude');
    lines.push('');
    for (const p of habits) {
      lines.push(`### ${p.title}`);
      lines.push('');
      lines.push(`Said ${p.count} times in ${p.sessions} sessions${p.projects.length > 1 ? ` across ${p.projects.length} projects` : ''}. Last on ${date(p.lastTs)}.`);
      lines.push('');
      for (const v of (p.variants || []).slice(0, 3)) lines.push(`> ${truncate(v.replace(/\s+/g, ' '), 200)}`);
      lines.push('');
      lines.push(`Suggested: **${SUGGESTION_LABEL[p.suggestion] || p.suggestion}** (${p.scope === 'global' ? 'personal' : 'project'})`);
      lines.push('');
      if (p.suggestion === 'rule') {
        lines.push('```markdown');
        lines.push(`- ${ruleText(p)}`);
        lines.push('```');
        lines.push('');
      }
    }
  }

  const briefs = patterns.filter((p) => p.kind === 'brief').slice(0, 6);
  if (briefs.length) {
    lines.push('## Briefs you paste again and again');
    lines.push('');
    for (const b of briefs) lines.push(`- **${truncate(b.text, 90)}**: pasted ${b.count} times in ${b.sessions} sessions (about ${b.words || '?'} words). A slash command would replace it.`);
    lines.push('');
  }

  if (health && health.length) {
    lines.push('## Memory health');
    lines.push('');
    lines.push('| Scope | Score | Rules | Top issue |');
    lines.push('|---|---|---|---|');
    for (const h of health.slice(0, 15)) lines.push(`| ${h.label} | ${h.score} (${h.grade}) | ${h.ruleCount} | ${h.issues[0] ? h.issues[0].title.replace(/\|/g, '/') : 'None'} |`);
    lines.push('');
  }

  const costly = [...sessions].sort((a, b) => b.costUSD - a.costUSD).slice(0, 8);
  if (costly.length) {
    lines.push('## Heaviest sessions');
    lines.push('');
    lines.push('| Session | Project | Date | Tokens | Cost | Compactions |');
    lines.push('|---|---|---|---|---|---|');
    for (const s of costly) lines.push(`| ${truncate(s.title.replace(/\|/g, '/'), 60)} | ${s.projectLabel} | ${date(s.start)} | ${fmtTokens(s.tokens)} | ${fmtUsd(s.costUSD)} | ${s.compactions} |`);
    lines.push('');
  }

  if (overview.tools.length) {
    lines.push('## How Claude worked');
    lines.push('');
    lines.push(overview.tools.slice(0, 8).map((x) => `${x.name} ${fmtInt(x.count)}`).join(', ') + '.');
    lines.push('');
  }
  lines.push('---');
  lines.push('Prompts are redacted for API keys and tokens. Costs use API list prices or the totals Claude Code recorded; on a subscription you are not billed per token.');
  lines.push('');
  return lines.join('\n');
}
