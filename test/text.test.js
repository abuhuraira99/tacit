import { test } from 'node:test';
import assert from 'node:assert/strict';
import { classifyUserText, cleanPrompt, normalize, splitClauses, trigrams, jaccard, slugify, contentWords } from '../src/core/text.js';
import { redact, containsSecret } from '../src/core/redact.js';

test('cleanPrompt removes injected wrappers but keeps what the person typed', () => {
  const raw = '<system-reminder>internal</system-reminder>\nfix the cart <ide_selection>lines 1-4</ide_selection> please';
  assert.equal(cleanPrompt(raw).replace(/\s+/g, ' '), 'fix the cart please');
  assert.ok(!cleanPrompt(raw).includes('internal'));
  assert.ok(!cleanPrompt(raw).includes('lines 1-4'));
  assert.ok(cleanPrompt(raw).startsWith('fix the cart'));
});

test('classifyUserText separates prompts, slash commands, interruptions and noise', () => {
  assert.equal(classifyUserText('[Request interrupted by user]').kind, 'interrupt');
  const cmd = classifyUserText('<command-name>/clear</command-name><command-message>clear</command-message>');
  assert.equal(cmd.kind, 'command');
  assert.equal(cmd.command, 'clear');
  assert.equal(classifyUserText('<system-reminder>x</system-reminder>').kind, 'noise');
  assert.equal(classifyUserText('Caveat: The messages below were generated by the user').kind, 'noise');
  assert.equal(classifyUserText('run the tests').kind, 'prompt');
});

test('normalize lowercases and strips punctuation', () => {
  assert.equal(normalize("Don't use `any`, OK?!"), 'dont use any ok');
});

test('splitClauses splits lists and sentences and drops code', () => {
  const clauses = splitClauses('1: use pnpm not npm\n2: run the tests before you finish. Also keep it short\n```js\nconst x = 1;\n```');
  assert.ok(clauses.includes('use pnpm not npm'));
  assert.ok(clauses.some((c) => c.startsWith('run the tests before you finish')));
  assert.ok(!clauses.some((c) => c.includes('const x')));
});

test('trigram similarity tolerates typos', () => {
  const a = trigrams('i want the best results no matter the token usage');
  const b = trigrams('i wnat the best results no matter teh token usage');
  assert.ok(jaccard(a, b) > 0.6);
  assert.ok(jaccard(a, trigrams('deploy the staging server')) < 0.2);
});

test('slugify and contentWords', () => {
  assert.equal(slugify('Run the tests before you say done!'), 'run-tests-before-say');
  assert.deepEqual(contentWords('Running the tests'), ['runn', 'test']);
});

test('redact removes keys, tokens and passwords', () => {
  const s = 'key sk-ant-api03-ABCDEFGHIJKLMNOPQRSTUV and ghp_abcdefghijklmnopqrstuvwxyz0123 and password=hunter2secret and https://bob:pa55word@host/x';
  const out = redact(s);
  assert.ok(!out.includes('sk-ant-api03'));
  assert.ok(!out.includes('ghp_abc'));
  assert.ok(!out.includes('hunter2secret'));
  assert.ok(!out.includes('pa55word'));
  assert.ok(containsSecret(s));
  assert.equal(redact('run the tests'), 'run the tests');
});
